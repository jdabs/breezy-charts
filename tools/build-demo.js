// Builds demo/index.html, a copy of the app that shows only simulated prices, for hosting publicly.
//
//   node tools/build-demo.js
//
// Run it after changing index.html. The demo copy has the Coinbase and Twelve Data sources and the
// API key field removed, not just hidden, so the hosted page cannot call either service. Each edit
// below must find its target exactly once; if index.html has changed so that one does not, the build
// stops with an error instead of producing a demo that still contains a live source.
'use strict';
const fs = require('fs'), path = require('path');

const REPO_URL = 'https://github.com/jdabs/breezy-charts';

function build(html){
  const eol = html.includes('\r\n') ? '\r\n' : '\n';
  let L = html.split(/\r?\n/);
  const find = (pred, what) => {
    const hits = L.map((l, i) => pred(l) ? i : -1).filter(i => i >= 0);
    if (hits.length !== 1) throw new Error(`build-demo: expected one ${what}, found ${hits.length}`);
    return hits[0];
  };
  const replace = (from, to) => {
    const i = find(l => l.includes(from), JSON.stringify(from));
    L[i] = L[i].replace(from, () => to);
  };

  // 1. say what this file is
  L.splice(find(l => l === '<!DOCTYPE html>', 'doctype') + 1, 0,
    '<!-- Generated from ../index.html by tools/build-demo.js. Do not edit this file: change index.html and run',
    '     node tools/build-demo.js. This copy shows simulated prices only and calls no market data service. -->');
  replace('<title>BreezyCharts</title>', '<title>BreezyCharts demo</title>');

  // 2. remove the live sources: everything in `providers` from Coinbase up to the Demo source
  const from = find(l => l === '  coinbase: {', 'Coinbase source'), to = find(l => l === '  demo: {', 'Demo source');
  if (to <= from) throw new Error('build-demo: the Demo source is expected after the live ones');
  L.splice(from, to - from);
  replace('/* ---- providers: Coinbase, Twelve Data, Demo ---- */', '/* ---- providers: Demo only (the live sources are removed from this copy) ---- */');
  replace("provider:'coinbase'", "provider:'demo'");               // the default source
  replace("state.provider = 'coinbase'", "state.provider = 'demo'"); // the fallback for a source that is not here

  // 3. remove the API key field; a hidden input keeps the settings code working with an empty key
  const label = find(l => l.trim().startsWith('<label for="tdKey">'), 'API key label');
  if (!L[label + 1].trim().startsWith('<input id="tdKey"') || !L[label + 2].trim().startsWith('<p>Free key at')) throw new Error('build-demo: the API key field is not as expected');
  L.splice(label, 3, '    <input id="tdKey" type="hidden">');

  // 4. header: a demo tag instead of the source picker, and a link to the full app
  replace('<div class="brand">Breezy<span>Charts</span></div>',
    '<div class="brand">Breezy<span>Charts</span></div>' + eol +
    '    <span class="demo-tag" title="Prices are generated in your browser. No market data is used.">Demo · simulated prices</span>');
  replace('<select id="providerSel" class="btn" title="Data source"></select>',
    `<a class="btn get-app" href="${REPO_URL}" target="_blank" rel="noopener" title="Download BreezyCharts to use it with live prices on your own computer">Get BreezyCharts ↗</a>` + eol +
    '    <select id="providerSel" class="btn" title="Data source" hidden></select>');
  L.splice(find(l => l === '</style>', 'end of the stylesheet'), 0,
    '  .demo-tag{font-size:12px;color:var(--warn);border:1px solid var(--warn);border-radius:10px;padding:1px 8px;white-space:nowrap}',
    '  .get-app{color:var(--text);text-decoration:none}');

  const out = L.join(eol);
  for (const host of ['coinbase.com', 'twelvedata.com']) if (out.includes(host)) throw new Error(`build-demo: "${host}" is still in the demo`);
  return out;
}

if (require.main === module) {
  const root = path.join(__dirname, '..');
  const out = build(fs.readFileSync(path.join(root, 'index.html'), 'utf8'));
  fs.mkdirSync(path.join(root, 'demo'), { recursive:true });
  fs.writeFileSync(path.join(root, 'demo', 'index.html'), out);
  console.log('Wrote demo/index.html');
}

module.exports = { build };
